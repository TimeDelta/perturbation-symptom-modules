"""The landing page of docs/ (experiments/generate_docs_index.py, written by the status generator): it links every
registered document, starts from documents that exist, files each under its topic whatever class directory it is in,
dates the records and marks the pages written before the stamp, gives a family of versions one line, counts what it
lists, and its check ignores nothing but the stamp."""
from __future__ import annotations

import re

from experiments.generate_docs_index import (
    BEFORE_THE_STAMP,
    INDEX_PATH,
    READ_FIRST,
    START_HERE,
    TOPICS,
    index_is_current,
    link,
    render_index,
    topic_of,
)
from mechanistic_pathway_learning.documentation import REPOSITORY_ROOT, load_registry, parse_stamp, strip_class_directory


def test_the_landing_page_links_every_registered_document_but_itself():
    text = render_index("Generated by `experiments/generate_docs_index.py` on 2026-10-17 at commit abc; do not edit by hand.")
    linked = set(re.findall(r"\]\(([^)]+)\)", text))
    own = str(INDEX_PATH.relative_to(REPOSITORY_ROOT))
    for path in load_registry():
        if path == own:
            assert link(path) not in linked, "the page does not list itself"
            continue
        assert link(path) in linked, f"{path} is registered but not on the landing page"


def test_the_start_list_names_registered_documents_and_every_registered_document_has_a_topic():
    registry = load_registry()
    assert all(path in registry for path, _, _ in START_HERE)
    untopiced = [path for path in registry if path != str(INDEX_PATH.relative_to(REPOSITORY_ROOT)) and topic_of(path) == "Other documents"]
    assert not untopiced, f"add a rule to TOPICS for {untopiced}"
    assert len({topic for topic, _ in TOPICS}) == len(TOPICS)


def test_links_are_relative_to_the_docs_directory():
    assert link("docs/status.md") == "status.md" and link("docs/exposure_sources/schulz2020.md") == "exposure_sources/schulz2020.md"
    assert link("README.md") == "../README.md"


def test_the_check_ignores_the_stamp_and_nothing_else():
    first = "# Documentation\n\nGenerated by `experiments/generate_docs_index.py` on 2026-10-16 at commit aaa; do not edit by hand.\n\n- [A](a.md)\n"
    second = first.replace("2026-10-16 at commit aaa", "2026-10-17 at commit bbb")
    assert index_is_current(first, second)
    assert not index_is_current(first, second.replace("[A](a.md)", "[B](b.md)"))


def test_the_committed_page_is_current():
    import subprocess

    result = subprocess.run(["python3", "experiments/generate_docs_index.py", "--check"], cwd=REPOSITORY_ROOT, capture_output=True, text=True,
                            env={"PYTHONPATH": str(REPOSITORY_ROOT), "PATH": "/usr/bin:/bin:/usr/local/bin"})
    assert result.returncode == 0, result.stdout + result.stderr


STAMP = "Generated by `experiments/generate_docs_index.py` on 2026-11-20 at commit abc; do not edit by hand."


def rendered_lines() -> list[str]:
    return render_index(STAMP).splitlines()


def line_linking(path: str, lines: list[str]) -> str:
    """The one entry of the topic lists (below the contents table) that links the document."""
    target = f"]({link(path)})"
    topics = lines[lines.index("## Contents"):]
    found = [line for line in topics if line.startswith("- ") and target in line]
    assert len(found) == 1, f"{path} is linked from {len(found)} entries of the topic lists"
    return found[0]


def test_topic_of_ignores_the_class_directory():
    """A TOPICS rule names a document by its name under docs/; the class directory a move puts it in is not part of it.
    The names here are made up, each matching a rule."""
    for plain in ("docs/phase9_fixture.md", "docs/design_review_2026-12-01.md", "docs/b6_fixture_modules.md",
                  "docs/mechanism_cards/fixture_run/anxiety.md", "docs/exposure_sources/fixture2020.md"):
        name = plain[len("docs/"):]
        for moved in (f"docs/generated/{name}", f"docs/records/2026-10/{name}", f"docs/drafts/{name}"):
            assert topic_of(moved) == topic_of(plain) != "Other documents", moved


def test_topic_rules_name_documents_without_their_class_directory():
    """topic_of strips the class directory before matching, so a rule written with one would never match."""
    patterns = [pattern for _, rules in TOPICS for pattern in rules]
    assert not [pattern for pattern in patterns if strip_class_directory(pattern) != pattern]


def test_records_carry_their_date_and_pages_before_the_stamp_are_marked():
    registry = load_registry()
    lines = rendered_lines()
    for path, entry in registry.items():
        if path == str(INDEX_PATH.relative_to(REPOSITORY_ROOT)) or entry.fields.get("family"):
            continue
        line = line_linking(path, lines)
        if entry.document_class == "record":
            assert f"(record, recorded {entry.fields['recorded']})" in line, line
        if entry.document_class == "generated" and parse_stamp((REPOSITORY_ROOT / path).read_text(encoding="utf-8")) is None:
            assert BEFORE_THE_STAMP in line, line
        elif entry.document_class == "generated":
            assert BEFORE_THE_STAMP not in line, line


def test_a_family_of_versions_is_one_line_linking_every_member():
    """One line per family, linking every member, and it names the one member the register marks current or says no
    member is on the v5 tables. Asked on 20 November 2026 which member of each family is current, the owner answered
    "6 yes" and then, asked which question 6, "Version families": the one generated on the tables the registered model
    reads, v5. So at most one member of a family carries `"current": true`."""
    registry = load_registry()
    lines = rendered_lines()
    families: dict[str, list[str]] = {}
    for path, entry in registry.items():
        if entry.fields.get("family") and entry.fields["family"] != "mechanism_cards":
            families.setdefault(entry.fields["family"], []).append(path)
    assert families, "the register names the families of versions"
    for family, members in families.items():
        holding = [line for line in lines if all(f"]({link(member)})" in line for member in members)]
        assert len(holding) == 1, f"family {family}: one line links all of {members}"
        assert f"{len(members)} versions" in holding[0] and ("no member on the v5 tables" in holding[0] or "current: " in holding[0])
        current = [member for member in members if registry[member].fields.get("current")]
        assert len(current) <= 1, f"family {family}: the v5 member is the current one, so at most one is marked: {current}"
        topics = lines[lines.index("## Contents"):]
        assert all(sum(f"]({link(member)})" in line for line in topics if line.startswith("- ")) == 1 for member in members)


def test_the_contents_table_counts_every_listed_document():
    """The contents table's counts add up to the documents each topic lists, and its total to every registered
    document but the page itself."""
    lines = rendered_lines()
    registry = load_registry()
    rows = [line for line in lines if line.startswith("| [")]
    total_row = next(line for line in lines if line.startswith("| all |"))
    sections: dict[str, list[str]] = {}
    current = None
    for line in lines:
        if line.startswith("## "):
            current = line[3:]
            sections[current] = []
        elif current and line.startswith("- "):
            sections[current].append(line)
    for row in rows:
        cells = [cell.strip() for cell in row.strip("|").split("|")]
        topic = cells[0][1:cells[0].index("](")]
        counts = [int(cell) for cell in cells[1:]]
        assert sum(counts[:-1]) == counts[-1], row
        linked = sum(1 for path in registry if path != str(INDEX_PATH.relative_to(REPOSITORY_ROOT))
                     and any(f"]({link(path)})" in line for line in sections[topic]))
        assert counts[-1] == linked, f"{topic}: the table counts {counts[-1]}, the section links {linked}"
    total = [int(cell.strip()) for cell in total_row.strip("|").split("|")[1:]]
    assert total[-1] == len(registry) - 1 == sum(int(row.strip("|").split("|")[-1]) for row in rows)


def test_the_page_reads_first_in_the_order_of_the_start_here_list():
    """READ_FIRST follows CLAUDE.md's Start-here list, with the register digest for configs/registered_rules.json."""
    claude = (REPOSITORY_ROOT / "CLAUDE.md").read_text(encoding="utf-8")
    start_here = claude.split("## Start here", 1)[1].split("\n## ", 1)[0]
    named = [path for path in ("docs/status.md", "configs/registered_rules.json", "docs/preregistration.md", "docs/open_decisions.md",
                               "docs/research_summary.md") if path in start_here]
    order = sorted(named, key=start_here.index)
    expected = [path.replace("configs/registered_rules.json", "docs/registered_core.md") for path in order]
    assert [path for path, _, _ in READ_FIRST] == expected


def test_the_reference_list_holds_the_exploration_queue_and_the_study_sheet_at_its_address():
    """Asked on 20 November 2026 whether the exploration queue and the study sheet should join the reference list,
    the owner answered "sure". The study sheet is kept current in Claude Docs, so its line links the doc at the
    address configs/study_sheet_diagrams.json records, then the registered Markdown copy."""
    import json

    lines = rendered_lines()
    reference = lines[lines.index("## Reference") + 1:lines.index("## Where documents live")]
    address = json.loads((REPOSITORY_ROOT / "configs" / "study_sheet_diagrams.json").read_text(encoding="utf-8"))["doc"]
    assert address.startswith("https://claude.ai/")
    assert sum(line.startswith("- [Exploration queue](exploration_queue.md): ") for line in reference) == 1
    sheet = [line for line in reference if line.startswith(f"- [Study sheet]({address}): ")]
    assert len(sheet) == 1 and "](study_sheet.md)" in sheet[0], reference


def test_the_page_says_where_a_new_document_goes():
    """Asked on 20 November 2026 whether CLAUDE.md should say where a new document goes, the owner answered "either
    there or the readme", and on 21 November 2026, asked which of the two, "Whichever makes more sense to you": the
    choice is this page. The rule is on it, under "Where documents live", and names each class directory of the
    placement rule (mechanistic_pathway_learning/documentation.py), so a change of directory shows here too."""
    from mechanistic_pathway_learning.documentation import DRAFTS_DIRECTORY, GENERATED_DIRECTORY, RECORDS_DIRECTORY

    lines = rendered_lines()
    section = lines[lines.index("## Where documents live") + 1:lines.index("## Contents")]
    rule = [line for line in section if line.startswith("**A new document**")]
    assert len(rule) == 1, section
    for directory in (GENERATED_DIRECTORY, RECORDS_DIRECTORY, DRAFTS_DIRECTORY):
        assert f"`{directory}/" in rule[0], directory
    assert '"either there or the readme"' in rule[0] and "20 November 2026" in rule[0]
