"""experiments/move_documents.py on a fixture repository (20 November 2026; docs/documentation_process.md, "Where
documents live"): what it rewrites and what it leaves, the allowance a generated page gets, the register key renamed
where it stands, the whole-path boundary, the check that a move is a pure rename, and the refusals."""
from __future__ import annotations

import json
import os
import subprocess

import pytest

from experiments.move_documents import apply_plan, plan_phase
from mechanistic_pathway_learning.documentation import moved_paths_text, registry_text

REGISTER = {
    "_what_this_is": "fixture",
    "documents": {
        "docs/living.md": {"class": "living", "reviewed": "2026-11-01", "as_of_commit": "abc1234"},
        "docs/old.md": {"class": "generated", "generator": "experiments/write_old.py"},
        "docs/old_v2.md": {"class": "generated", "generator": "experiments/write_old.py"},
        "docs/page.md": {"class": "generated", "generator": "experiments/write_page.py"},
        "docs/record.md": {"class": "record", "recorded": "2026-10-05", "append_only": True},
    },
}
FILES = {
    "docs/old.md": "# Old\n\nGenerated by experiments/write_old.py.\n",
    "docs/old_v2.md": "# Old, version 2\n\nGenerated by experiments/write_old.py.\n",
    "docs/living.md": "# Living\n\nThe table is `docs/old.md`; [the table](old.md); its second version is `docs/old_v2.md`.\n",
    "docs/page.md": "# Page\n\nGenerated by experiments/write_page.py from `docs/old.md`.\n",
    "docs/record.md": "# Record\n\nOn 5 October the table `docs/old.md` said so.\n",
    "experiments/write_old.py": 'OUTPUT = "docs/old.md"  # and docs/old_v2.md for the second version\nOTHER = "../docs/old.md"\n',
    "configs/run.yaml": "table: docs/old.md\n",
    "configs/table.csv": "row,source\n1,docs/old.md\n",
}


def git(root, *arguments: str) -> str:
    environment = {**os.environ, "GIT_AUTHOR_NAME": "t", "GIT_AUTHOR_EMAIL": "t@t", "GIT_COMMITTER_NAME": "t", "GIT_COMMITTER_EMAIL": "t@t"}
    return subprocess.run(["git", "-C", str(root), *arguments], check=True, capture_output=True, text=True, env=environment).stdout


@pytest.fixture
def repository(tmp_path):
    git(tmp_path, "init", "-q")
    for name, text in FILES.items():
        (tmp_path / name).parent.mkdir(parents=True, exist_ok=True)
        (tmp_path / name).write_text(text)
    (tmp_path / "configs" / "documentation_registry.json").write_text(registry_text(REGISTER))
    moved = {"_what_this_is": "fixture", "moves": [], "planned": [{"from": "docs/old.md", "to": "docs/generated/old.md", "phase": 1},
                                                                  {"from": "docs/record.md", "to": "docs/records/2026-10/record.md", "phase": 2}]}
    (tmp_path / "configs" / "moved_paths.json").write_text(moved_paths_text(moved))
    git(tmp_path, "add", ".")
    git(tmp_path, "commit", "-q", "-m", "fixture")
    return tmp_path


def test_the_dry_run_rewrites_whole_paths_and_links_and_leaves_records_and_tables(repository):
    plan = plan_phase(1, root=repository)
    assert not plan.refusals, plan.refusals
    rewritten = {source: [after for _, _, after in edits] for source, edits in plan.edits.items()}
    assert rewritten["docs/living.md"] == ["The table is `docs/generated/old.md`; [the table](generated/old.md); its second version is `docs/old_v2.md`."]
    assert rewritten["experiments/write_old.py"] == ['OUTPUT = "docs/generated/old.md"  # and docs/old_v2.md for the second version']
    assert rewritten["configs/run.yaml"] == ["table: docs/generated/old.md"]
    assert set(rewritten) == {"docs/living.md", "experiments/write_old.py", "configs/run.yaml"}, "records and tables are left as written"
    assert {kind: [source for source, _, _ in rows] for kind, rows in plan.left.items()} == {
        "record": ["docs/record.md"], "configs table or quotation": ["configs/table.csv"]}
    assert set(plan.allowances) == {"docs/page.md"} and set(plan.allowances["docs/page.md"]) == {"docs/old.md"}
    assert plan.key_renames == {"docs/old.md": "docs/generated/old.md"}
    assert any(source == "experiments/write_old.py" and "../docs/old.md" in what for source, _, what in plan.by_hand), \
        "an old path behind a prefix the whole-path rule leaves alone is listed for a hand edit"


def test_apply_moves_by_pure_rename_renames_the_key_in_place_and_records_the_move(repository):
    plan = plan_phase(1, root=repository)
    assert apply_plan(plan, root=repository) == []
    assert "R100\tdocs/old.md\tdocs/generated/old.md" in git(repository, "diff", "--cached", "-M100%", "--name-status")
    register_text = (repository / "configs" / "documentation_registry.json").read_text()
    keys = list(json.loads(register_text)["documents"])
    assert keys == ["docs/living.md", "docs/generated/old.md", "docs/old_v2.md", "docs/page.md", "docs/record.md"], "renamed where it stood"
    page = json.loads(register_text)["documents"]["docs/page.md"]
    assert "moved to `docs/generated/old.md`" in page["names_absent_paths"]["docs/old.md"]
    moved = json.loads((repository / "configs" / "moved_paths.json").read_text())
    assert [entry["from"] for entry in moved["moves"]] == ["docs/old.md"] and moved["moves"][0]["date"]
    assert [entry["from"] for entry in moved["planned"]] == ["docs/record.md"], "the other phase stays planned"
    assert (repository / "docs" / "record.md").read_text() == FILES["docs/record.md"], "a record keeps the old path as written"
    assert "docs/old_v2.md" in (repository / "experiments" / "write_old.py").read_text(), "docs/old.md is not matched inside docs/old_v2.md"
    diff = git(repository, "diff", "--cached", "--", "configs/documentation_registry.json")
    changed = [line for line in diff.splitlines() if line[:1] in "+-" and not line.startswith(("+++", "---"))]
    assert len(changed) <= 8, f"the register changes on its own lines only: {changed}"


def test_it_refuses_when_a_destination_exists_or_a_file_it_touches_has_uncommitted_changes(repository):
    (repository / "docs" / "generated").mkdir()
    (repository / "docs" / "generated" / "old.md").write_text("in the way\n")
    assert any("exists already" in why for why in plan_phase(1, root=repository).refusals)
    (repository / "docs" / "generated" / "old.md").unlink()
    (repository / "docs" / "living.md").write_text(FILES["docs/living.md"] + "an edit not yet committed\n")
    assert any("docs/living.md has uncommitted changes" in why for why in plan_phase(1, root=repository).refusals)


def test_it_refuses_an_unregistered_document_and_a_shallow_clone(repository, tmp_path_factory):
    register = json.loads((repository / "configs" / "documentation_registry.json").read_text())
    del register["documents"]["docs/old.md"]
    (repository / "configs" / "documentation_registry.json").write_text(registry_text(register))
    git(repository, "commit", "-q", "-am", "unregister")
    assert any("the register does not name" in why for why in plan_phase(1, root=repository).refusals)
    clone = tmp_path_factory.mktemp("clone")
    subprocess.run(["git", "clone", "-q", "--depth", "1", f"file://{repository}", str(clone)], check=True, capture_output=True)
    assert any("shallow" in why for why in plan_phase(1, root=clone).refusals)


def test_a_relative_link_that_would_break_is_refused(repository):
    (repository / "docs" / "old.md").write_text(FILES["docs/old.md"] + "\nSee [the living page](living.md).\n")
    git(repository, "commit", "-q", "-am", "a link out of the moving page")
    assert any("would not resolve" in why for why in plan_phase(1, root=repository).refusals)
