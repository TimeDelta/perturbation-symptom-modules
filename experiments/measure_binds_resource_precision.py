"""Measure the precision of each OmniPath resource that supplies binds edges against HuRI's tested space (decision 9.91).

The method is that of Venkatesan et al. 2009 (doi 10.1038/nmeth.1280), who retested samples of each interaction dataset
in MAPPIT beside a positive reference set (hsPRS) and a random reference set (hsRRS) and read precision as the dataset's
retest rate placed between the two: precision = (f - f_random) / (f_reference - f_random) (their LC, single-publication
dataset: 10% retested against 34% and 2%, precision 25%). Here the "retest" is HuRI's nine screens of one search
space, which every pair of two tested proteins went through:
  - f, per resource: of the resource's binds pairs (the graph's binds edges of the signalling family that the
    resource states in the raw OmniPath table) with both proteins tested, the fraction HuRI detected. A resource is not
    credited with a pair for which every reference it gives is a CCSB screen paper (IntAct deposits HuRI's pairs under
    HuRI's paper), so a resource that imported HuRI is scored on the rest of its pairs;
  - f_reference: the same fraction for Lit-BM, the binary literature pairs with at least two pieces of evidence that
    the HuRI paper used as its reference ("Lit-BM"), from interactome-atlas.org;
  - f_random: the exact rate for a uniformly random pair of two tested proteins (HuRI's pairs among them over all such
    pairs), the expectation of a random reference set without its sampling error.
OmniPath imports HuRI and Lit-BM (its resources "HuRI" and "Lit-BM-17"); they are not scored, since scoring a source
against itself measures nothing. The tested set is the one graph/huri_tested_space.py uses (the genes with at least one
HuRI interaction, since Space III's list could not be read; docs/data_sources.md).

What it measures and does not. Y2H detects direct binary binding. A resource whose pairs are co-complex members,
ligand-receptor pairs needing a cell surface or interactions needing a modification yeast does not make scores low for
reasons other than error, so the number is a precision for direct binary binding, the claim a binds edge makes, and a
lower bound for "associated". The interval carries the binomial interval of f alone; Lit-BM's and the random rate's
uncertainty is smaller and is left out. A report only: nothing here sets a weight (decision 9.91).

Usage:
  python experiments/measure_binds_resource_precision.py --graph-dir data/processed/graph_full_neuronal_split_binders_drugs_v5
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
import sys
from pathlib import Path

import pandas as pd

from mechanistic_pathway_learning.documentation import provenance_stamp
from mechanistic_pathway_learning.graph import huri_tested_space as huri

DEFAULT_OUTPUT = Path("docs/binds_resource_precision.md")
MINIMUM_PAIRS_FOR_A_READING = 30


def percent(value: float) -> str:
    return "-" if value is None or (isinstance(value, float) and math.isnan(value)) else f"{100 * value:.1f}%"


def write_report(path: Path, result: dict, stamp: str, graph_dir: Path) -> None:
    reference, random = result["reference_lit_bm"], result["random_pairs"]
    graph_pairs = result["all_graph_binds_pairs"]
    lines = ["# Precision of the binds resources against HuRI (generated by experiments/measure_binds_resource_precision.py)", "", stamp, "",
             f"Graph `{graph_dir}` (edges.parquet sha256 first 16 {result['edges_sha256'][:16]}). Decision 9.91's measurement, a report that sets no weight. Method (Venkatesan et al. 2009): a resource's "
             "detection rate in HuRI's tested space placed between that of Lit-BM (a positive reference set) and that of a random pair of tested "
             "proteins, precision = (f - f_random) / (f_Lit-BM - f_random). The tested space is the "
             f"{random['tested_genes']:,} genes with at least one HuRI interaction (Space III's list could not be read). HuRI and Lit-BM are not "
             "scored: OmniPath imports both, and no resource is credited with a pair it cites only from a CCSB screen paper. A low value can mean co-complex, ligand-receptor or modification-dependent pairs that a yeast "
             "two-hybrid screen cannot detect, not only error.", "",
             "| reference | pairs inside the tested space | detected by HuRI | rate |", "| --- | --- | --- | --- |",
             f"| Lit-BM | {reference['pairs_inside_tested_space']:,} | {reference['detected']:,} | {percent(reference['rate'])} "
             f"({percent(reference['rate_95_interval'][0])} to {percent(reference['rate_95_interval'][1])}) |",
             f"| random pair of tested proteins (exact) | {random['possible_pairs']:,} | {random['detected']:,} | {100 * random['rate']:.3f}% |",
             f"| every binds pair of the graph (signalling family) | {graph_pairs['pairs_inside_tested_space']:,} | {graph_pairs['detected']:,} | {percent(graph_pairs['rate'])}; "
             f"precision {percent(huri.precision_from_rates(graph_pairs['rate'], reference['rate'], random['rate']))} |",
             "", f"Resources with at least {MINIMUM_PAIRS_FOR_A_READING} pairs inside the tested space, by precision; the interval is the 95% "
             "Wilson interval of the resource's rate carried through the formula.", "",
             "| resource | binds pairs | inside the tested space | detected | rate | precision | 95% interval |", "| --- | --- | --- | --- | --- | --- | --- |"]
    scored = {name: entry for name, entry in result["by_resource"].items() if entry["pairs_inside_tested_space"] >= MINIMUM_PAIRS_FOR_A_READING}
    for name, entry in sorted(scored.items(), key=lambda item: -item[1]["precision"]):
        low, high = entry["precision_95_interval"]
        lines.append(f"| {name} | {entry['binds_pairs']:,} | {entry['pairs_inside_tested_space']:,} | {entry['detected']:,} | {percent(entry['rate'])} | "
                     f"{percent(entry['precision'])} | {percent(low)} to {percent(high)} |")
    fewer = sorted(name for name, entry in result["by_resource"].items() if entry["pairs_inside_tested_space"] < MINIMUM_PAIRS_FOR_A_READING)
    lines += ["", f"Not read (fewer than {MINIMUM_PAIRS_FOR_A_READING} pairs inside the tested space): {', '.join(fewer) if fewer else 'none'}.", ""]
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--graph-dir", type=Path, required=True)
    parser.add_argument("--huri", type=Path, default=huri.DEFAULT_HURI)
    parser.add_argument("--lit-bm", type=Path, default=huri.DEFAULT_LIT_BM)
    parser.add_argument("--hgnc", type=Path, default=huri.DEFAULT_HGNC)
    parser.add_argument("--space-iii-genes", type=Path, default=None)
    parser.add_argument("--omnipath", type=Path, default=Path("data/raw/omnipath/omnipath_interactions.tsv"))
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    arguments = parser.parse_args()
    evidence = pd.read_parquet(arguments.graph_dir / "edge_evidence.parquet", columns=["source_id", "target_id", "relation_type", "family"])
    symbol_of_ensembl = huri.symbol_of_ensembl_gene(arguments.hgnc)
    huri_pairs, huri_mapping = huri.symbol_pairs(huri.read_ensembl_pairs(arguments.huri), symbol_of_ensembl)
    lit_bm_pairs, lit_bm_mapping = huri.symbol_pairs(huri.read_ensembl_pairs(arguments.lit_bm), symbol_of_ensembl)
    space = set(arguments.space_iii_genes.read_text(encoding="utf-8").split()) if arguments.space_iii_genes else None
    tested = huri.tested_genes(huri_pairs, space)
    graph_pairs = huri.graph_binds_pairs(evidence)
    omnipath = pd.read_csv(arguments.omnipath, sep="\t", usecols=["source_genesymbol", "target_genesymbol", "sources", "references"])
    result = huri.resource_precision(huri.resource_pairs(omnipath, graph_pairs), graph_pairs, huri_pairs, lit_bm_pairs, tested)
    result.update({"graph_dir": str(arguments.graph_dir), "edges_sha256": hashlib.sha256((arguments.graph_dir / "edges.parquet").read_bytes()).hexdigest(),
                   "huri_mapping": huri_mapping, "lit_bm_mapping": lit_bm_mapping})
    stamp = provenance_stamp("experiments/measure_binds_resource_precision.py",
                             [f"{arguments.graph_dir}/edge_evidence.parquet", str(arguments.omnipath), str(arguments.huri), str(arguments.lit_bm), str(arguments.hgnc)])
    write_report(arguments.output, result, stamp, arguments.graph_dir)
    arguments.output.with_suffix(".json").write_text(json.dumps(result, indent=1, default=float) + "\n", encoding="utf-8")
    print(f"wrote {arguments.output}: Lit-BM {percent(result['reference_lit_bm']['rate'])}, random {100 * result['random_pairs']['rate']:.3f}%, "
          f"{len(result['by_resource'])} resources")
    return 0


if __name__ == "__main__":
    sys.exit(main())
