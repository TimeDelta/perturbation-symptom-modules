"""Build the fine symptom crosswalk from the coarse one (decision 9.58).

Reads docs/symptom_crosswalk.csv, configs/symptom_construct_additions.csv, configs/fine_construct_term_overrides.csv,
configs/fine_construct_extra_roots.csv, configs/fine_construct_kept_together.csv, hp.obo and the SIDER MedDRA vocabulary; writes docs/symptom_crosswalk_fine.csv, configs/impc_symptom_crosswalk_fine.csv
and docs/generated/fine_symptom_constructs.md (generated, stamped). The rules are in evidence/symptom_constructs.py: a coarse
row's terms are shared out among its HPO roots by the ontology's own vocabulary, an added construct takes the MedDRA
preferred terms whose words the ontology uses for it, an extra root splits a construct out below a coarse row's roots
without changing the coarse row, a coarse row named in the kept-together table is not split at its roots, a MeSH
descriptor stays with the coarse row's namesake unless an override names its
D-number, an IMPC proxy goes to the fine construct an override names for one of its MP term ids before the name match,
and every assignment is listed with how it was made.

Usage:
  python experiments/build_fine_symptom_crosswalk.py
  python experiments/build_fine_symptom_crosswalk.py --check   # exit 1 when the committed files differ from a fresh build
"""
from __future__ import annotations

import argparse
import csv
import gzip
import sys
from pathlib import Path

from mechanistic_pathway_learning.documentation import provenance_stamp
from mechanistic_pathway_learning.evidence.symptom_constructs import (
    ADDITIONS_PATH,
    COARSE_CROSSWALK_PATH,
    EXTRA_ROOTS_PATH,
    KEPT_TOGETHER_PATH,
    CROSSWALK_COLUMNS,
    FINE_COLUMNS,
    FINE_CROSSWALK_PATH,
    IMPC_COARSE_PATH,
    IMPC_COLUMNS,
    IMPC_FINE_PATH,
    TERM_OVERRIDES_PATH,
    HpoVocabulary,
    annotate_extra_roots,
    build_fine_crosswalk,
    fine_impc_rows,
    phrase,
    read_extra_roots,
    read_kept_together,
    read_rows,
    read_term_overrides,
    split_cell,
    with_extra_roots,
    write_rows,
)

DEFAULT_OBO = Path("data/raw/hpo/hp.obo")
DEFAULT_SIDER_SIDE_EFFECTS = Path("data/raw/sider_4.1/meddra_all_se.tsv.gz")
DEFAULT_PAGE = Path("docs/generated/fine_symptom_constructs.md")


def meddra_preferred_terms(path: Path) -> list[str]:
    """Every distinct MedDRA preferred term name SIDER uses (column 6 of rows whose column 4 is PT)."""
    terms = set()
    with gzip.open(path, "rt", encoding="utf-8") as handle:
        for row in csv.reader(handle, delimiter="\t"):
            if len(row) >= 6 and row[3] == "PT":
                terms.add(row[5])
    return sorted(terms)


def complete_addition(addition: dict[str, str], vocabulary: HpoVocabulary, preferred_terms: list[str]) -> dict[str, str]:
    """An added construct named by id only: its name from the ontology, its MedDRA terms the preferred terms whose
    words the ontology uses for the root or a kept descendant."""
    root_id = split_cell(addition.get("hpo_ids"))[0]
    phrases = vocabulary.phrases_of(root_id, split_cell(addition.get("excluded_hpo_ids")))
    matched = [term for term in preferred_terms if phrase(term) in phrases]
    completed = {column: addition.get(column, "") for column in CROSSWALK_COLUMNS}
    completed["hpo_names"] = vocabulary.names_by_term[root_id]
    completed["meddra_preferred_terms"] = ";".join(matched)
    completed.setdefault("identifier_status", "")
    completed["identifier_status"] = completed["identifier_status"] or "hpo id and name read from hp.obo; MedDRA terms matched from the vocabulary; MeSH unverified"
    return completed


def render(stamp: str, fine_rows: list[dict[str, str]], assignments: list[dict[str, str]], impc_rows: list[dict[str, str]],
           extra_roots: list[dict[str, str]] | None = None, kept_together: list[dict[str, str]] | None = None) -> str:
    coarse_count = len({row["coarse_symptom"] for row in fine_rows})
    lines = ["# The fine symptom constructs (generated by experiments/build_fine_symptom_crosswalk.py — do not edit by hand)", "", stamp, "",
             f"{len(fine_rows)} fine constructs from {coarse_count} coarse ones. A coarse construct with several HPO roots is split at those roots; each "
             "fine construct is named by its root's HPO name, so none is authored here. Merging is left to the model (decision 9.58)."
             + (" The exceptions are listed under \"Constructs whose roots are kept together\"." if kept_together else ""), "",
             "| fine construct | coarse construct | HPO root | MedDRA preferred terms |", "| --- | --- | --- | --- |"]
    for row in fine_rows:
        lines.append(f"| {row['target_symptom']} | {row['coarse_symptom']} | {row['hpo_ids']} {row['hpo_names']} | {row['meddra_preferred_terms'].replace(';', '; ')} |")
    if extra_roots:
        lines += ["", "## Constructs split out below a coarse construct's roots", "",
                  "Each row of configs/fine_construct_extra_roots.csv adds an HPO term under one of a coarse construct's roots as a root of that "
                  "construct for this derivation only: the coarse crosswalk as registered is unchanged, and so is what the coarse construct covers. "
                  "The parent construct excludes the added root, as it does any sibling root under it.", "",
                  "| coarse construct | added root | RDoC domain | decision | note |", "| --- | --- | --- | --- | --- |"]
        for extra in extra_roots:
            domain = (extra.get("rdoc_domain") or "").strip() or "the coarse row's"
            lines.append(f"| {extra['coarse_symptom']} | {extra['hpo_id']} {extra['hpo_name']} | {domain} | {extra['decision']} | {extra.get('note', '')} |")
    if kept_together:
        roots_by_construct = {row["target_symptom"]: f"{row['hpo_ids']} {row['hpo_names']}".replace(";", "; ") for row in fine_rows}
        lines += ["", "## Constructs whose roots are kept together", "",
                  "Each row of configs/fine_construct_kept_together.csv names a coarse construct that is not split at its roots: it stays one fine "
                  "construct under its coarse name and holds every root. Each is an exception to one construct per root, with its reason.", "",
                  "| construct | roots | date | note |", "| --- | --- | --- | --- |"]
        for kept in kept_together:
            lines.append(f"| {kept['coarse_symptom']} | {roots_by_construct.get(kept['coarse_symptom'].strip(), '')} | {kept['date']} | {kept['note']} |")
    lines += ["", "## How each MedDRA term of a split coarse construct was assigned", "",
              "`override` is a row of configs/fine_construct_term_overrides.csv; `hpo vocabulary` means the term's words are a name or synonym in the "
              "construct's HPO expansion; `stem match` means the term shares word stems with the root's own name or synonyms; `namesake` means nothing "
              "decided and the term went to the coarse construct's namesake root. Move any of them with an override.", "",
              "| coarse construct | term | fine construct | how |", "| --- | --- | --- | --- |"]
    term_assignments = [assignment for assignment in assignments if assignment["kind"] == "meddra"]
    for assignment in term_assignments:
        if assignment["how"] != "single construct":
            lines.append(f"| {assignment['coarse_symptom']} | {assignment['term']} | {assignment['fine_construct']} | {assignment['how']} |")
    by_how: dict[str, int] = {}
    for assignment in term_assignments:
        by_how[assignment["how"]] = by_how.get(assignment["how"], 0) + 1
    lines += ["", "Counts: " + ", ".join(f"{how} {count}" for how, count in sorted(by_how.items())) + "."]
    moved_descriptors = [assignment for assignment in assignments if assignment["kind"] == "mesh"]
    if moved_descriptors:
        lines += ["", "## MeSH descriptors moved from the namesake", "",
                  "A coarse construct's MeSH descriptors stay with its namesake unless a row of configs/fine_construct_term_overrides.csv names a "
                  "descriptor's D-number; the level travels with the descriptor.", "",
                  "| coarse construct | descriptor | fine construct |", "| --- | --- | --- |"]
        lines += [f"| {assignment['coarse_symptom']} | {assignment['term']} | {assignment['fine_construct']} |" for assignment in moved_descriptors]
    lines += ["",
              "## The IMPC crosswalk at the fine level", "",
              "A coarse row's mouse proxy goes to the fine construct a row of configs/fine_construct_term_overrides.csv names for one of its "
              "MP term ids, else to the one its MP term names match, else to the namesake.", "",
              "| fine construct | relation | MP terms | validity |", "| --- | --- | --- | --- |"]
    for row in impc_rows:
        lines.append(f"| {row['target_symptom']} | {row['relation']} | {row['mp_term_names'] or '-'} | {row['validity']} |")
    lines.append("")
    return "\n".join(lines)


def checked_kept_together(coarse_rows: list[dict[str, str]], vocabulary: HpoVocabulary) -> list[dict[str, str]]:
    """The kept-together table, refused when a row names no coarse construct with several roots, or one whose roots
    lie one under another (the lower root would then add nothing)."""
    kept_together = read_kept_together(KEPT_TOGETHER_PATH)
    by_name = {row["target_symptom"]: row for row in coarse_rows}
    for kept in kept_together:
        coarse = kept["coarse_symptom"].strip()
        root_ids = split_cell(by_name.get(coarse, {}).get("hpo_ids"))
        if len(root_ids) < 2:
            raise ValueError(f"{KEPT_TOGETHER_PATH} names {coarse!r}, which is not a coarse construct with several HPO roots")
        nested = [root for root in root_ids if any(other in vocabulary.ancestors_of(root) for other in root_ids)]
        if nested:
            raise ValueError(f"{coarse}: {nested} lie under another root of the row")
    return kept_together


def build(obo: Path, sider: Path) -> tuple[list[dict[str, str]], list[dict[str, str]], list[dict[str, str]], list[dict[str, str]]]:
    vocabulary = HpoVocabulary.from_obo(obo)
    preferred_terms = meddra_preferred_terms(sider)
    extra_roots = read_extra_roots(EXTRA_ROOTS_PATH)
    coarse_rows = with_extra_roots(read_rows(COARSE_CROSSWALK_PATH), extra_roots, vocabulary)
    additions = [complete_addition(addition, vocabulary, preferred_terms) for addition in read_rows(ADDITIONS_PATH)] if ADDITIONS_PATH.exists() else []
    overrides = read_term_overrides(TERM_OVERRIDES_PATH)
    fine_rows, assignments = build_fine_crosswalk(coarse_rows, additions, overrides, vocabulary)
    fine_rows = annotate_extra_roots(fine_rows, extra_roots)
    impc_rows = fine_impc_rows(read_rows(IMPC_COARSE_PATH), coarse_rows, additions, overrides)
    return fine_rows, assignments, impc_rows, extra_roots


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--obo", type=Path, default=DEFAULT_OBO)
    parser.add_argument("--sider-side-effects", type=Path, default=DEFAULT_SIDER_SIDE_EFFECTS)
    parser.add_argument("--page", type=Path, default=DEFAULT_PAGE)
    parser.add_argument("--check", action="store_true", help="compare a fresh build with the committed files and change nothing")
    arguments = parser.parse_args()
    fine_rows, assignments, impc_rows, extra_roots = build(arguments.obo, arguments.sider_side_effects)
    kept_together = checked_kept_together(read_rows(COARSE_CROSSWALK_PATH), HpoVocabulary.from_obo(arguments.obo))
    if arguments.check:
        committed = read_rows(FINE_CROSSWALK_PATH) if FINE_CROSSWALK_PATH.exists() else []
        fresh = [{column: row.get(column, "") for column in FINE_COLUMNS} for row in fine_rows]
        committed = [{column: row.get(column, "") for column in FINE_COLUMNS} for row in committed]
        if fresh != committed:
            print(f"{FINE_CROSSWALK_PATH} differs from a fresh build; rerun without --check")
            return 1
        print(f"{FINE_CROSSWALK_PATH} is current")
        return 0
    write_rows(FINE_CROSSWALK_PATH, fine_rows, FINE_COLUMNS)
    write_rows(IMPC_FINE_PATH, impc_rows, IMPC_COLUMNS)
    stamp = provenance_stamp("experiments/build_fine_symptom_crosswalk.py", [str(COARSE_CROSSWALK_PATH), str(ADDITIONS_PATH), str(TERM_OVERRIDES_PATH), str(EXTRA_ROOTS_PATH), str(KEPT_TOGETHER_PATH),
                                                                         str(IMPC_COARSE_PATH), "hp.obo", "SIDER meddra_all_se"])
    arguments.page.write_text(render(stamp, fine_rows, assignments, impc_rows, extra_roots, kept_together), encoding="utf-8")
    print(f"wrote {FINE_CROSSWALK_PATH} ({len(fine_rows)} constructs), {IMPC_FINE_PATH} ({len(impc_rows)} rows), {arguments.page}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
