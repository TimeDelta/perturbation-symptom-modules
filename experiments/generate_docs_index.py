def document_title(path: Path) -> str:
    """The first level-one heading, without the "(generated by ... do not edit by hand)" it may end with."""
    try:
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.startswith("# "):
                return GENERATED_SUFFIX.sub("", line[2:].strip()) or path.name
    except OSError:
        pass
    return path.name


def topic_of(path: str) -> str:
    """The first topic whose TOPICS rule matches the path without its class directory (docs/generated/x.md is
    matched as docs/x.md), so a rule keeps working when its documents move."""
    plain = strip_class_directory(path)
    for topic, patterns in TOPICS:
        if any(fnmatch.fnmatch(plain, pattern) for pattern in patterns):
            return topic
    return OTHER_TOPIC


def link(path: str) -> str:
    """A link from docs/README.md to a repository path."""
    return path[len("docs/"):] if path.startswith("docs/") else f"../{path}"


def study_sheet_address(root: Path = REPOSITORY_ROOT) -> str:
    """The Claude Docs address of the owner's study sheet, as configs/study_sheet_diagrams.json records it."""
    address = json.loads((root / STUDY_SHEET_DIAGRAMS).read_text(encoding="utf-8")).get("doc", "")
    if not address.startswith("https://"):
        raise ValueError(f"{STUDY_SHEET_DIAGRAMS} gives no https address for the study sheet under \"doc\": {address!r}")
    return address


def start_line(path: str, label: str, reason: str, root: Path = REPOSITORY_ROOT) -> str:
    """One line of the start lists. The study sheet's links the doc, which is the version kept current, and then the
    Markdown copy in the repository; every other line links its document."""
    if path == STUDY_SHEET_COPY:
        return f"- [{label}]({study_sheet_address(root)}): {reason} ([its Markdown copy]({link(path)}), refreshed by exporting the doc)"
    return f"- [{label}]({link(path)}): {reason}"


def anchor(heading: str) -> str:
    """The fragment GitHub gives a heading: lower case, punctuation dropped, spaces as hyphens."""
    return re.sub(r"[^\w\- ]", "", heading.lower()).replace(" ", "-")


def document_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def listing_kind(document_class: str, text: str) -> str:
    """The document's place in LISTING_ORDER: its class, with generated pages split by whether they carry the stamp."""
    if document_class == "generated":
        return "stamped" if parse_stamp(text) else "before the stamp"
    return document_class


def document_line(path: str, document, kind: str, title: str) -> str:
    what = document.fields.get("what")
    if document.document_class == "frozen":
        what = f"the copy frozen on {document.fields.get('frozen_on', 'its date')}, pinned by its SHA-256"
    label = CLASS_LABELS[document.document_class]
    if kind == "record" and document.fields.get("recorded"):
        label = f"record, recorded {document.fields['recorded']}"
    elif kind == "before the stamp":
        label = f"generated, {BEFORE_THE_STAMP}"
    suffix = f": {what.rstrip('.')}" if what else ""
    return f"- [{title}]({link(path)}) ({label}){suffix}."


def family_line(name: str, members: list[str], entries: dict, kinds: dict, titles: dict) -> str:
    """One line for a family of versions: the members' shared title, how many there are, which one (if any) the
    register marks current (`"current": true` on that member's entry, beside its `family`), and a link to each.

    The current member is the one generated on the tables the registered model reads, v5 (the owner, 21 November 2026,
    "Version families"), so a family the register marks none in has no member on those tables, and every version of it
    is history until one is regenerated."""
    members = sorted(members)
    shared = {titles[member] for member in members}
    title = shared.pop() if len(shared) == 1 else f"`{name}`"
    current = [member for member in members if entries[member].fields.get("current")]
    state = (("current: " + ", ".join(f"[`{Path(member).stem}`]({link(member)})" for member in current)) if current
             else "no member on the v5 tables, so none is current")
    before = sum(kinds[member] == "before the stamp" for member in members)
    if before == len(members):
        label = f"generated, all {BEFORE_THE_STAMP}"
    elif before == 0:
        label = "generated, stamped"
    else:
        label = f"generated; {len(members) - before} stamped, {before} {BEFORE_THE_STAMP}"
    links = ", ".join(f"[`{Path(member).stem}`]({link(member)})" for member in members)
    return f"- {title}: {len(members)} versions, {state} ({label}): {links}."


